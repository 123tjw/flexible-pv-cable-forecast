def Coord1dPosEncoding(q_len, exponential=False, normalize=True):
    cpe = (2 * (torch.linspace(0, 1, q_len).reshape(-1, 1)**(.5 if exponential else 1)) - 1)
    if normalize:
        cpe = cpe - cpe.mean()
        cpe = cpe / (cpe.std() * 10)
    return cpe

def positional_encoding(pe, learn_pe, q_len, d_model):
    # Positional encoding
    if pe == None:
        W_pos = torch.empty((q_len, d_model)) # pe = None and learn_pe = False can be used to measure impact of pe
        nn.init.uniform_(W_pos, -0.02, 0.02)
        learn_pe = False
    elif pe == 'zero':
        W_pos = torch.empty((q_len, 1))
        nn.init.uniform_(W_pos, -0.02, 0.02)
    elif pe == 'zeros':
        W_pos = torch.empty((q_len, d_model))
        nn.init.uniform_(W_pos, -0.02, 0.02)
    elif pe == 'normal' or pe == 'gauss':
        W_pos = torch.zeros((q_len, 1))
        torch.nn.init.normal_(W_pos, mean=0.0, std=0.1)
    elif pe == 'uniform':
        W_pos = torch.zeros((q_len, 1))
        nn.init.uniform_(W_pos, a=0.0, b=0.1)
    elif pe == 'lin1d': W_pos = Coord1dPosEncoding(q_len, exponential=False, normalize=True)
    elif pe == 'exp1d': W_pos = Coord1dPosEncoding(q_len, exponential=True, normalize=True)
    elif pe == 'lin2d': W_pos = Coord2dPosEncoding(q_len, d_model, exponential=False, normalize=True)
    elif pe == 'exp2d': W_pos = Coord2dPosEncoding(q_len, d_model, exponential=True, normalize=True)
    elif pe == 'sincos': W_pos = PositionalEncoding(q_len, d_model, normalize=True)
    else: raise ValueError(f"{pe} is not a valid pe (positional encoder. Available types: 'gauss'=='normal', \
        'zeros', 'zero', uniform', 'lin1d', 'exp1d', 'lin2d', 'exp2d', 'sincos', None.)")
    return nn.Parameter(W_pos, requires_grad=learn_pe)


class PatchwiseChannelAttention(nn.Module):
    """Patch-level cross-channel attention.

    Operates on [B, C, P, D] by reshaping to [B*P, C, D] and computing
    multi-head attention across the C (channel) dimension. Each temporal
    position independently learns which channels are important.

    Physical motivation for PV cable monitoring:
    - temperature -> tension (thermal expansion)
    - wind speed -> vibration -> deflection (aerodynamic coupling)
    The model learns these dependencies at every time step.
    """

    def __init__(self, d_model, n_heads=4, attn_dropout=0., proj_dropout=0.):
        super().__init__()
        assert d_model % n_heads == 0, f"d_model ({d_model}) must be divisible by n_heads ({n_heads})"
        self.n_heads = n_heads
        self.d_k = d_model // n_heads

        self.W_Q = nn.Linear(d_model, d_model, bias=False)
        self.W_K = nn.Linear(d_model, d_model, bias=False)
        self.W_V = nn.Linear(d_model, d_model, bias=False)
        self.W_O = nn.Linear(d_model, d_model, bias=False)

        self.attn_dropout = nn.Dropout(attn_dropout)
        self.proj_dropout = nn.Dropout(proj_dropout)
        self.scale = self.d_k ** -0.5

    def forward(self, x, return_attn=False):
        """
        x: [B, C, P, D]  (B=batch, C=channels, P=patch_num, D=d_model)
        Returns: [B, C, P, D]
        """
        B, C, P, D = x.shape

        # Reshape: treat each temporal position independently
        x_flat = x.permute(0, 2, 1, 3).reshape(B * P, C, D)  # [B*P, C, D]

        # QKV projections
        Q = self.W_Q(x_flat).view(B * P, C, self.n_heads, self.d_k).transpose(1, 2)  # [B*P, H, C, dk]
        K = self.W_K(x_flat).view(B * P, C, self.n_heads, self.d_k).transpose(1, 2)
        V = self.W_V(x_flat).view(B * P, C, self.n_heads, self.d_k).transpose(1, 2)

        # Attention: [B*P, H, C, dk] x [B*P, H, dk, C] -> [B*P, H, C, C]
        scores = torch.matmul(Q, K.transpose(-2, -1)) * self.scale
        attn_weights = F.softmax(scores, dim=-1)
        attn_weights = self.attn_dropout(attn_weights)

        # Weighted sum: [B*P, H, C, C] x [B*P, H, C, dk] -> [B*P, H, C, dk]
        out = torch.matmul(attn_weights, V)
        out = out.transpose(1, 2).contiguous().view(B * P, C, D)  # [B*P, C, D]
        out = self.W_O(out)
        out = self.proj_dropout(out)

        # Reshape back: [B*P, C, D] -> [B, P, C, D] -> [B, C, P, D]
        out = out.view(B, P, C, D).permute(0, 2, 1, 3)

        if return_attn:
            return out, attn_weights.view(B, P, self.n_heads, C, C)
        return out